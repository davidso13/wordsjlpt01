const toHiragana = s => s.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));

export function parseWordFile(text) {
  const days = { ...DAY_NAMES };
  for (const m of text.matchAll(/DAY\s*0?(\d+)\s*[-:]\s*([^()]+?)\s*\(/g)) days[+m[1]] = m[2].trim();
  const re = /(\d{3})[.:]\s*([^\s()（）:]+)\s*(?:[（(]([^)）]+)[)）])?\s*[:\-–]\s*(.+?)(?=\s{2,}|\s*DAY\s|\d{3}[.:]\s|$)/g;
  const out = [];
  for (const m of text.matchAll(re)) {
    const no = +m[1], word = m[2].trim();
    const day = Math.floor((no - 1) / 25) + 1;
    const ex = EXAMPLES[word] || ['', ''];
    out.push({
      no: m[1], word,
      reading: (m[3] || toHiragana(word)).trim(),
      meaning: m[4].trim(),
      example: ex[0], example_ko: ex[1],
      section: `DAY ${String(day).padStart(2, '0')}${days[day] ? ' · ' + days[day] : ''}`,
    });
  }
  return out;
}

async function main() {
  await ensureSchema();
  for (const d of DECKS) {
    const [exists] = await sql`select id from decks where source_file = ${d.file}`;
    if (exists) { console.log(`skip  ${d.name} (${d.file}) — 이미 저장됨, id=${exists.id}`); continue; }
    const words = normalizeWords(parseWordFile(readFileSync(new URL(`../data/${d.file}`, import.meta.url), 'utf8')));
    const missing = words.filter(w => !w.example).map(w => w.word);
    if (missing.length) throw new Error(`예문이 없는 단어: ${missing.join(', ')}`);
    const deck = await insertDeck({ name: d.name, source: 'file', sourceFile: d.file, words });
    console.log(`saved ${d.name} id=${deck.id} words=${deck.word_count}`);
  }
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())) {
  main().catch(e => { console.error(e); process.exit(1); });
}
